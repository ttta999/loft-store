test('уведомления учитывают уменьшение движения', async ({ page }, info) => {
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto(ADMIN)
  await page.getByTitle('Уведомления о новых заказах и спецзаказах', { exact: true }).click()
  const menu = page.locator('[data-notification-menu]')
  await expect(menu).toBeVisible()
  expect(await menu.evaluate(e => Number(getComputedStyle(e).opacity))).toBe(1)
  const bounds = await menu.boundingBox()
  expect(bounds!.x).toBeGreaterThanOrEqual(0)
  expect(bounds!.x + bounds!.width).toBeLessThanOrEqual(page.viewportSize()!.width)
  await page.screenshot({ path: info.outputPath('notifications.png') })
  await page.keyboard.press('Escape')
  await expect(menu).toHaveCount(0)
})
