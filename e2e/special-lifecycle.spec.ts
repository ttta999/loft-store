import { test, expect, STORE, ADMIN, productId } from './fixture'
import type { Page } from '@playwright/test'
async function regular(page: Page) {
 await page.goto(`${STORE}/product/${productId}`)
 await page.locator('[data-dialog-trigger="size"]').click()
 await page.getByRole('button',{name:'42',exact:true}).click()
 await page.getByRole('button',{name:'В корзину',exact:true}).click()
 await expect(page.getByText('Товар добавлен в корзину!',{exact:true})).toBeVisible()
}
async function special(page: Page,id=3001) {
 await page.goto(STORE+'/profile?section=china')
 await page.locator(`[data-profile-link="request:${id}"]`).click()
 await page.locator('.loft-detail').getByRole('button',{name:'Добавить в корзину',exact:true}).click()
}
async function checkout(page: Page) {
 await page.getByRole('button',{name:/Корзина$/}).click()
 await page.getByRole('button',{name:'Оформить заказ',exact:true}).click()
 await page.getByPlaceholder('Ваше имя',{exact:true}).fill('Покупатель')
 await page.getByPlaceholder('+998 XX XXX XX XX',{exact:true}).fill('+998901234567')
}

test('несколько спецзаказов и обычный товар: одна корзина, без дублей, общий заказ и ссылки в обеих панелях',async({page,context,harness})=>{
 Object.assign(harness.db.china_requests[0],{status:'Оценён',manager_price:100})
 harness.db.china_requests.push({...harness.db.china_requests[0],id:3002,product_name:'Второй спецзаказ',manager_price:50})
 await regular(page)
 await special(page)
 await special(page)
 expect(await page.evaluate(()=>JSON.parse(localStorage.getItem('loft-store')!).state.cart.length)).toBe(2)
 await special(page,3002)
 expect(harness.db.china_requests.map(r=>r.status)).toEqual(['Оценён','Оценён'])
 await checkout(page)
 await expect(page.getByRole('radio',{name:'Оплата при получении',exact:true})).toBeVisible()
 await page.getByRole('radio',{name:'Оплата при получении',exact:true}).check()
 await page.getByRole('button',{name:'Подтвердить заказ',exact:true}).click()
 await expect(page.getByText('Заказ оформлен!',{exact:true})).toBeVisible()
 expect(harness.db.orders.find(o=>o.id===2001)!.items).toHaveLength(3)
 expect(harness.db.china_requests.map(r=>[r.status,r.converted_to_order_id])).toEqual([['Оформлен','2001'],['Оформлен','2001']])
 await page.getByRole('button',{name:'Готово',exact:true}).click()
 await page.goto(STORE+'/profile?section=china')
 await page.locator('[data-profile-link="request:3001"]').click()
 await expect(page.locator('.loft-detail').getByRole('button',{name:'Добавить в корзину',exact:true})).toHaveCount(0)
 await page.getByRole('button',{name:'Перейти к заказу',exact:true}).click()
 await expect(page).toHaveURL(STORE+'/profile?section=orders&order=2001')
 await expect(page.locator('.loft-detail').getByText('Заказ №2001',{exact:true})).toBeVisible()
 const manager=await context.newPage()
 await manager.goto(ADMIN+'/china')
 await manager.getByRole('button',{name:/Спецзаказ №3001/}).click()
 await expect(manager.getByRole('button',{name:'Оплачен',exact:true})).toHaveCount(0)
 await manager.getByRole('button',{name:'Перейти к заказу №2001',exact:true}).click()
 await expect(manager).toHaveURL(ADMIN+'/orders?order=2001')
 await expect(manager.getByText('Спецзаказ №3001, №3002',{exact:true})).toBeVisible()
})

