import { readFile, readdir } from 'node:fs/promises'
import { spawnSync } from 'node:child_process'
import assert from 'node:assert/strict'

const container = 'supabase_db_loft-security-local'
const endpoint = spawnSync('docker', ['context', 'inspect', '--format', '{{.Endpoints.docker.Host}}'], { encoding: 'utf8' })
assert.match(endpoint.stdout.trim(), /^unix:\/\//, 'Use a local Docker context')
const inspect = spawnSync('docker', ['inspect', container], { encoding: 'utf8' })
assert.equal(inspect.status, 0, 'Start the dedicated local Supabase stack first')
const [database] = JSON.parse(inspect.stdout)
assert.deepEqual(Object.keys(database.NetworkSettings.Networks), ['loft-security-loopback'])
assert.deepEqual(database.NetworkSettings.Ports['5432/tcp'], [{ HostIp: '127.0.0.1', HostPort: '56322' }])

const read = path => readFile(new URL('../../' + path, import.meta.url), 'utf8')
const baseline = await read('tests/sql/store2-baseline.sql')
const tables = baseline.slice(baseline.indexOf('create table public.brands'), baseline.indexOf('create table public.refunds'))
  + baseline.slice(baseline.indexOf('create table public.settings'), baseline.indexOf('create table private.store_outbox'))

const setup = `
begin;
do $$ begin
  if to_regclass('public.products') is not null then
    raise exception 'Bootstrap requires a fresh local database';
  end if;
end $$;
create extension if not exists pgcrypto with schema extensions;
-- Supabase runs the provider schemas. Only application-managed base tables are synthetic.
-- Intercept the two worker wakeup calls, even if real extensions are bundled in the image.
drop extension if exists pg_net;
create schema if not exists net;
create function net.http_post(url text, headers jsonb, body jsonb, timeout_milliseconds integer)
returns bigint language sql as $$ select 0::bigint $$;
revoke all on schema net from public, anon, authenticated, service_role;
${tables}
alter table public.orders drop column checkout_abandoned_at, drop column special_fulfillment,
  drop column cancelled_by, drop column cancelled_at, drop column cancellation_reason,
  drop column payment_amount, drop column payment_currency;
alter table public.china_requests drop column reserved_order_id, drop column rejection_reason;
create table public.category_change_logs (
  id bigint generated by default as identity primary key,
  action text not null, entity_type text not null, entity_id text not null,
  admin_email text, changes jsonb, created_at timestamptz not null default now()
);
insert into public.settings(key,value) values
  ('exchange_rate','{"rate":12000}'),
  ('sale_mode_enabled','{"enabled":false}'),
  ('delivery_price','{"price":0}'),
  ('free_delivery_threshold','{"amount":0}'),
  ('payment_cards','{"UZS":{"number":"0000000000000000","holder":"Fixture"},"USD":{"number":"0000000000000000","holder":"Fixture"}}');
create function public.delete_unpaid_order(bigint) returns void language sql as $$ select null::void $$;
alter table public.product_colors add foreign key (product_id) references public.products on delete cascade;
alter table public.product_variants add foreign key (product_id) references public.products on delete cascade;
alter table public.product_variants add foreign key (color_id) references public.product_colors on delete cascade;
insert into storage.buckets(id,name,public) values
  ('product-images','product-images',true),
  ('payment-screenshots','payment-screenshots',false),
  ('china-requests','china-requests',false);
`

const legacy = ['01_store_backend', '02_lockdown', '04_admin_operations', '07_reservation_lifecycle',
  '08_order_currency_guard', '09_admin_mfa_and_payment_audit', '10_enforce_admin_mfa', '14_payment_confirmation_guard']
const patches = []
for (const file of legacy) {
  let sql = await read(`db/${file}.sql`)
  if (file === '01_store_backend') {
    // The historical bootstrap names an infrastructure-managed account. Never seed it locally.
    sql = sql.replace(/^insert into private\.store_admins\(user_id\) values .*;\r?$/m, '')
    assert.ok(!/insert into private\.store_admins\(user_id\) values/i.test(sql))
  }
  patches.push('\\echo Applying ' + file + '\n' + sql)
}
const dir = new URL('../../supabase/migrations/', import.meta.url)
for (const filename of (await readdir(dir)).filter(filename => filename.endsWith('.sql')).sort()) {
  // The integration test installs this migration over a real, enrolled legacy administrator.
  if (filename === '20261126183000_require_verified_admin_mfa.sql') continue
  let sql = await read(`supabase/migrations/${filename}`)
  sql = sql.replace(/^create extension if not exists pg_net with schema extensions;\r?$/gm, '')
  assert.ok(!/^create extension.*pg_net/im.test(sql))
  if (filename.endsWith('_configurable_payment_cards.sql')) {
    sql = sql.replace(/^insert into public\.settings\(key,value\) values\('payment_cards'.*;\r?$/m, '')
    assert.ok(!/^insert.*'payment_cards'/im.test(sql))
  }
  patches.push('\\echo Applying ' + filename + '\n' + sql)
}
const result = spawnSync('docker', ['exec', '-i', container, 'psql', '-X', '-q', '-v', 'ON_ERROR_STOP=1', '-U', 'postgres', 'postgres'], {
  input: [setup, ...patches, `select cron.alter_job(jobid,active:=false) from cron.job where jobname like 'loft-%';
    notify pgrst, 'reload schema'; commit;`].join('\n'),
  encoding: 'utf8',
  maxBuffer: 4_000_000,
})
if (result.status !== 0) {
  console.error(result.stdout.split('\n').filter(line => line.startsWith('Applying ')).at(-1))
  console.error(result.stderr.split('\n').filter(line => /^ERROR:|^DETAIL:|^CONTEXT:/.test(line)).join('\n'))
  process.exitCode = 1
} else {
  console.log(`Applied ${patches.length} application SQL files to dedicated local PostgreSQL. Worker forwarding is inert.`)
}
