-- Only a stored order exchange-rate snapshot may fill an old UZS amount.
create function private.store_order_amount(o public.orders,c text) returns numeric language sql immutable set search_path='' as $$
 select case when c='USD' and o.total_price_usd>=0 then o.total_price_usd
 when c='UZS' and o.total_price_uzs>=0 then o.total_price_uzs
 when c='UZS' and o.total_price_usd>=0 and o.exchange_rate_at_order>0 then round(o.total_price_usd*o.exchange_rate_at_order) else null end;
$$;
create function private.store_queue_event(p_key text,p_user text,p_order bigint,p_payload jsonb) returns void
language sql security invoker set search_path='' as $$
 insert into private.store_outbox(event_key,user_id,order_id,kind,payload) values(p_key,p_user,p_order,'custom',p_payload) on conflict(event_key) do nothing;
$$;
create function private.store_queue_ordinary_order(p_id bigint) returns void language plpgsql security invoker set search_path='' as $$
declare o public.orders%rowtype; stage text;
begin
 select * into o from public.orders where id=p_id;
 if not found or o.special_fulfillment or o.checkout_abandoned_at is not null or o.status='Отменён' then return; end if;
 if o.payment_method='online_card' and o.status<>'Ожидает оплаты' and (o.payment_status is distinct from 'paid' or o.paid_at is null) then return; end if;
 stage:=case o.status when 'Ожидает оплаты' then case when o.receipt_submitted_at is not null then 'На обработке' end
 when 'Активный' then 'Принят' when 'В обработке' then 'Собирается'
 when 'Готов' then case when o.delivery_method='pickup' then 'Готов к выдаче' else 'Упакован' end
 when 'Выдан' then case when o.delivery_method='pickup' then 'Получен' else 'Передан курьеру' end
 when 'Доставлен' then 'Доставлен' end;
 if stage is null then return; end if;
 perform private.store_queue_event('ordinary-order-status:'||o.id||':'||stage,o.user_id,o.id,
 jsonb_build_object('ordinary_order',jsonb_build_object('id',o.id,'stage',stage,'delivery_method',o.delivery_method,
 'payment_method',o.payment_method,'amount',private.store_order_amount(o,o.order_currency),'currency',o.order_currency,'courier_link',o.courier_link)));
end $$;

create function private.store_prepare_refund(o public.orders) returns jsonb language plpgsql security invoker set search_path='' as $$
declare r public.refunds%rowtype; a numeric; c text; s text;
begin
 select * into r from public.refunds where order_id=o.id;
 if found then return to_jsonb(r); end if;
 if o.paid_at is null and o.receipt_submitted_at is null and o.payment_screenshot_url is null and o.payment_status is distinct from 'refund_pending' then return null; end if;
 if o.paid_at is not null and o.payment_status in ('paid','refund_pending') then
  c:=coalesce(o.payment_currency,o.order_currency);
  if c not in ('USD','UZS') then c:=null; end if;
  a:=case when o.payment_currency is not null and o.payment_amount is not null then o.payment_amount else private.store_order_amount(o,c) end;
 end if;
 s:=case when a>0 and c in ('USD','UZS') then 'Ожидает возврата' when a=0 and c in ('USD','UZS') then 'Возврат не требуется' else 'Проверка платежа' end;
 insert into public.refunds(order_id,user_id,status,amount,currency,order_amount,order_currency,reason,cancelled_by)
 values(o.id,o.user_id,s,a,c,private.store_order_amount(o,o.order_currency),case when o.order_currency in ('USD','UZS') then o.order_currency end,o.cancellation_reason,o.cancelled_by)
 on conflict(order_id) do nothing returning * into r;
 if not found then select * into r from public.refunds where order_id=o.id; else
 insert into private.store_refund_audit(refund_id,actor_id,action,current_state) values(r.id,auth.uid(),'created',to_jsonb(r)); end if;
 return to_jsonb(r);
end $$;

create function private.store_queue_refund(r public.refunds) returns void language sql security invoker set search_path='' as $$
 select private.store_queue_event('refund-status:'||r.id||':'||r.revision||':'||r.status,r.user_id,r.order_id,
 jsonb_build_object('refund',jsonb_build_object('id',r.id,'order_id',r.order_id,'status',r.status,'amount',r.amount,'currency',r.currency)));
$$;

create function public.store_admin_refund_action(p_id bigint,p_action text,p_key uuid,p_amount numeric default null,p_currency text default null,p_comment text default null,p_proof text default null)
returns jsonb language plpgsql security definer set search_path='' as $$
declare r public.refunds%rowtype; previous jsonb; o public.orders%rowtype; input jsonb; old_request jsonb; old_action text; path text;
begin
 if not public.store_is_admin() then raise insufficient_privilege; end if;
 if p_key is null or p_action is null then raise exception 'Некорректный запрос'; end if;
 select * into r from public.refunds where id=p_id;
 if not found then raise exception 'Возврат недоступен'; end if;
 perform pg_advisory_xact_lock(hashtextextended('store-user:'||r.user_id,0));
 select * into o from public.orders where id=r.order_id for update;
 select * into r from public.refunds where id=p_id for update;
 input:=jsonb_build_object('action',p_action,'amount',p_amount,'currency',p_currency,'comment',p_comment,'proof',p_proof);
 select action,request_data into old_action,old_request from private.store_refund_audit where refund_id=r.id and request_key=p_key;
 if found then
  if old_action<>p_action or old_request is distinct from input then raise exception 'Повторный запрос содержит другие данные'; end if;
  return to_jsonb(r);
 end if;
 if o.status<>'Отменён' then raise exception 'Заказ не отменён'; end if;
 previous:=to_jsonb(r);
 if p_action='claim' then
  if r.status='Возврат выполнен' then raise exception 'Возврат уже завершён'; end if;
  if r.assigned_to is not null and r.assigned_to<>auth.uid() then raise exception 'Возврат уже обрабатывает другой менеджер'; end if;
  update public.refunds set assigned_to=auth.uid(),assigned_at=coalesce(assigned_at,now()),updated_at=now() where id=r.id returning * into r;
 else
  if r.assigned_to is distinct from auth.uid() then raise exception 'Сначала возьмите возврат в работу'; end if;
  if length(coalesce(p_comment,''))>2000 then raise exception 'Комментарий слишком длинный'; end if;
  if p_action='payment_received' then
   if r.status not in ('Проверка платежа','Возврат не требуется') then raise exception 'Платёж уже проверен'; end if;
   if r.status='Возврат не требуется' and length(btrim(coalesce(p_comment,'')))<3 then raise exception 'Укажите причину повторной проверки'; end if;
   if p_currency is null or p_currency not in ('USD','UZS') or p_amount is null or not(p_amount>0 and p_amount<=1000000000000) or p_amount<>round(p_amount,case when p_currency='USD' then 2 else 0 end) then raise exception 'Укажите фактически полученную сумму и валюту'; end if;
   update public.refunds set status='Ожидает возврата',amount=p_amount,currency=p_currency,manager_comment=nullif(btrim(p_comment),''),processed_by=auth.uid(),reviewed_at=now(),updated_at=now(),revision=revision+case when r.status='Возврат не требуется' then 1 else 0 end where id=r.id returning * into r;
   update public.orders set payment_status='refund_pending',payment_amount=p_amount,payment_currency=p_currency,paid_at=coalesce(paid_at,now()),payment_provider=coalesce(payment_provider,'manual') where id=o.id;
   perform private.store_queue_refund(r);
  elsif p_action='no_payment' then
   if r.status<>'Проверка платежа' then raise exception 'Платёж уже проверен'; end if;
   update public.refunds set status='Возврат не требуется',amount=null,currency=null,manager_comment=nullif(btrim(p_comment),''),processed_by=auth.uid(),reviewed_at=now(),updated_at=now(),assigned_to=null,assigned_at=null where id=r.id returning * into r;
   update public.orders set payment_status='cancelled' where id=o.id;
   perform private.store_queue_refund(r);
  elsif p_action='proof' then
   if r.status<>'Ожидает возврата' then raise exception 'Возврат недоступен для загрузки квитанции'; end if;
   if p_proof is null or left(p_proof,22)<>'private:refund-proofs/' then raise exception 'Некорректная квитанция'; end if;
   path:=substr(p_proof,23);
   if path !~ '^[0-9]+/[0-9a-f-]+/[0-9a-f-]+\.(png|jpg|jpeg|webp|pdf)$' or split_part(path,'/',1)<>r.id::text or split_part(path,'/',2)<>auth.uid()::text then raise exception 'Некорректная квитанция'; end if;
   if not exists(select 1 from storage.objects f where f.bucket_id='refund-proofs' and f.name=path and coalesce(f.owner_id,f.owner::text)=auth.uid()::text and (f.metadata->>'size')::bigint between 1 and 8388608 and f.metadata->>'mimetype' in ('image/jpeg','image/png','image/webp','application/pdf')) then raise exception 'Файл квитанции не найден'; end if;
   update public.refunds set proof_url=p_proof,updated_at=now() where id=r.id returning * into r;
  elsif p_action='complete' then
   if r.status<>'Ожидает возврата' then raise exception 'Возврат уже завершён или ещё не подтверждён'; end if;
   if r.proof_url is null then raise exception 'Загрузите квитанцию фактического обратного перевода'; end if;
   if not exists(select 1 from storage.objects f where f.bucket_id='refund-proofs' and f.name=substr(r.proof_url,23)) then raise exception 'Квитанция недоступна'; end if;
   update public.refunds set status='Возврат выполнен',completed_at=now(),processed_by=auth.uid(),updated_at=now() where id=r.id returning * into r;
   update public.orders set payment_status='refunded' where id=o.id;
   perform private.store_queue_refund(r);
  else raise exception 'Недопустимое действие возврата'; end if;
 end if;
 insert into private.store_refund_audit(refund_id,actor_id,action,request_key,previous_state,current_state,request_data)
 values(r.id,auth.uid(),p_action,p_key,previous,to_jsonb(r),input);
 begin perform private.store_wake_worker(); exception when others then null; end;
 return to_jsonb(r);
end $$;

-- A manager can explicitly open a payment check when a transfer is reported only after cancellation.
create function public.store_admin_open_refund(p_order_id bigint,p_reason text) returns jsonb
language plpgsql security definer set search_path='' as $$
declare o public.orders%rowtype; r public.refunds%rowtype;
begin
 if not public.store_is_admin() then raise insufficient_privilege; end if;
 if length(btrim(coalesce(p_reason,''))) not between 3 and 1000 then raise exception 'Укажите основание проверки платежа'; end if;
 select * into o from public.orders where id=p_order_id;
 if not found then raise exception 'Заказ недоступен'; end if;
 perform pg_advisory_xact_lock(hashtextextended('store-user:'||o.user_id,0));
 select * into o from public.orders where id=p_order_id for update;
 if o.status<>'Отменён' then raise exception 'Заказ не отменён'; end if;
 select * into r from public.refunds where order_id=o.id;
 if found then return to_jsonb(r); end if;
 insert into public.refunds(order_id,user_id,status,order_amount,order_currency,reason,cancelled_by,manager_comment)
 values(o.id,o.user_id,'Проверка платежа',private.store_order_amount(o,o.order_currency),case when o.order_currency in ('USD','UZS') then o.order_currency end,o.cancellation_reason,o.cancelled_by,p_reason) returning * into r;
 insert into private.store_refund_audit(refund_id,actor_id,action,current_state) values(r.id,auth.uid(),'late_payment_check',to_jsonb(r));
 return to_jsonb(r);
end $$;

create function public.store_admin_refund_history(p_id bigint) returns jsonb language plpgsql security definer set search_path='' as $$
begin
 if not public.store_is_admin() then raise insufficient_privilege; end if;
 return coalesce((select jsonb_agg(to_jsonb(a) order by a.id) from private.store_refund_audit a where a.refund_id=p_id),'[]');
end $$;

create function private.store_queue_cancellation(o public.orders,r jsonb) returns void language plpgsql security invoker set search_path='' as $$
declare snapshot jsonb;
begin
 if o.checkout_abandoned_at is not null then return; end if;
 snapshot:=jsonb_build_object('id',o.id,'source',o.cancelled_by,'reason',o.cancellation_reason,'special',o.special_fulfillment,
 'refund_status',r->>'status','amount',r->'amount','currency',r->>'currency');
 perform private.store_queue_event('order-cancelled:'||o.id,o.user_id,o.id,jsonb_build_object('cancellation',snapshot));
 if o.cancelled_by='client' then perform private.store_queue_event('order-cancelled-manager:'||o.id,o.user_id,o.id,
 jsonb_build_object('cancellation',snapshot,'recipient','manager')); end if;
end $$;

create function private.store_cancel_order_internal(p_user text,p_id bigint,p_source text,p_reason text default null,p_manual boolean default false)
returns boolean language plpgsql security invoker set search_path='' as $$
declare o public.orders%rowtype; item jsonb; draft boolean; r jsonb;
begin
 if p_source is null or p_source not in ('client','store','system') then raise exception 'Некорректный источник отмены'; end if;
 if p_source='store' and not public.store_is_admin() then raise insufficient_privilege; end if;
 perform pg_advisory_xact_lock(hashtextextended('store-user:'||p_user,0));
 select * into o from public.orders where id=p_id and user_id=p_user for update;
 if not found then return false; end if;
 if o.status='Отменён' or o.checkout_abandoned_at is not null then return true; end if;
 draft:=o.payment_method='online_card' and o.status='Ожидает оплаты' and o.payment_status='pending' and o.paid_at is null and o.receipt_submitted_at is null and o.payment_screenshot_url is null;
 if p_source='system' and not draft then return false; end if;
 if p_source='client' and not draft and (o.status not in ('Ожидает оплаты','Активный') or ((o.special_fulfillment or o.special_order_id is not null or exists(select 1 from jsonb_array_elements(o.items) i where i->>'isSpecialOrder'='true')) and o.payment_status<>'pending')) then return false; end if;
 if o.status in ('Получен','Доставлен') or (o.status='Выдан' and o.delivery_method='pickup') then return false; end if;
 if p_source='store' then
  p_reason:=btrim(coalesce(p_reason,''));
  if length(p_reason) not between 1 and 1000 then raise exception 'Укажите причину отмены'; end if;
  if ((o.delivery_method='delivery' and o.status in ('Выдан','Передан курьеру')) or (o.special_fulfillment and o.status in ('Заказан у поставщика','В пути','Прибыл в страну','Собирается','Готов к выдаче','Упакован','Передан курьеру'))) and not p_manual then raise exception 'Сначала согласуйте отмену вручную'; end if;
 end if;
 if not o.stock_released then
  for item in select value from jsonb_array_elements(o.items) order by value->>'productId',value->>'size',value->>'colorId' loop
   if not coalesce((item->>'isSpecialOrder')::boolean,false) then
    update public.product_variants set stock=stock+(item->>'quantity')::integer where product_id::text=item->>'productId' and size_value=item->>'size' and color_id::text is not distinct from nullif(item->>'colorId','');
   end if;
  end loop;
 end if;
 -- Never reopen an already paid/converted quote. Only temporary reservations are released.
 update public.china_requests set reserved_order_id=null where reserved_order_id=o.id;
 o.cancelled_by:=case when draft then 'system' else p_source end; o.cancelled_at:=clock_timestamp();
 o.cancellation_reason:=case when p_source='store' then p_reason else null end;
 if not draft then r:=private.store_prepare_refund(o); end if;
 update public.orders set status='Отменён',stock_released=true,cancelled_by=o.cancelled_by,cancelled_at=o.cancelled_at,cancellation_reason=o.cancellation_reason,
 payment_status=case r->>'status' when 'Ожидает возврата' then 'refund_pending' when 'Проверка платежа' then 'payment_review' else 'cancelled' end,
 checkout_abandoned_at=case when draft then clock_timestamp() else checkout_abandoned_at end,reservation_expires_at=null
 where id=o.id returning * into o;
 update private.store_outbox set sent_at=clock_timestamp() where order_id=o.id and user_id=o.user_id and sent_at is null
 and (kind in ('order','order_client') or payload->'ordinary_order' is not null or payload->'special_order' is not null);
 if not draft then perform private.store_queue_cancellation(o,r); end if;
 begin perform private.store_wake_worker(); exception when others then null; end;
 return true;
end $$;

create or replace function public.store_cancel_order(p_user text,p_order_id bigint,p_delete boolean default false) returns boolean
language plpgsql security invoker set search_path='' as $$
declare o public.orders%rowtype;
begin
 perform pg_advisory_xact_lock(hashtextextended('store-user:'||p_user,0));
 select * into o from public.orders where id=p_order_id and user_id=p_user for update;
 if not found then return false; end if;
 if o.checkout_abandoned_at is not null then return true; end if;
 if p_delete and not(o.payment_method='online_card' and o.status='Ожидает оплаты' and o.payment_status='pending' and o.paid_at is null and o.receipt_submitted_at is null and o.payment_screenshot_url is null) then return false; end if;
 return private.store_cancel_order_internal(p_user,p_order_id,case when p_delete then 'system' else 'client' end);
end $$;

create function public.store_admin_cancel_order_reason(p_order_id bigint,p_reason text,p_manual boolean default false) returns jsonb
language plpgsql security definer set search_path='' as $$
