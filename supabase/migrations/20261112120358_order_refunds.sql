 amount numeric check(amount>=0), currency text check(currency in ('USD','UZS')),
 order_amount numeric, order_currency text check(order_currency in ('USD','UZS')),
 reason text, cancelled_by text check(cancelled_by in ('client','store','system')),
 proof_url text, manager_comment text,
 assigned_to uuid, assigned_at timestamptz,
 processed_by uuid, reviewed_at timestamptz,
 revision integer not null default 1,
 created_at timestamptz not null default now(), updated_at timestamptz not null default now(), completed_at timestamptz,
 check(status not in ('Ожидает возврата','Возврат выполнен') or (amount>0 and amount is not null and currency is not null)),
 check(status<>'Возврат выполнен' or (proof_url is not null and completed_at is not null and processed_by is not null))
);
