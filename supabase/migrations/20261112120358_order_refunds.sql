create or replace function private.store_queue_order_notifications(p_order_id bigint) returns void language sql security invoker set search_path='' as $$
 select private.store_finalize_special_requests(p_order_id);
 insert into private.store_outbox(event_key,user_id,order_id,kind)
 select 'order:'||o.id,o.user_id,o.id,'order' from public.orders o where o.id=p_order_id and o.checkout_abandoned_at is null and o.status<>'Отменён'
 and (o.payment_method<>'online_card' or o.receipt_submitted_at is not null or o.payment_status='paid') on conflict(event_key) do nothing;
 select private.store_queue_ordinary_order(p_order_id);
 select private.store_queue_special_order(p_order_id);
$$;

